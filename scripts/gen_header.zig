const std = @import("std");

pub fn main(init: std.process.Init) !void {
    var arena = std.heap.ArenaAllocator.init(init.gpa);
    defer arena.deinit();
    const allocator = arena.allocator();

    var args_list = try std.ArrayList([]const u8).initCapacity(allocator, 16);
    var args_iter = std.process.Args.Iterator.init(init.minimal.args);
    while (args_iter.next()) |arg| {
        try args_list.append(allocator, try allocator.dupe(u8, arg));
    }
    const args = args_list.items;

    if (args.len < 2) {
        std.debug.print("Usage: gen_header <output_path>\n", .{});
        return;
    }

    const output_path = args[1];

    // Create the header content
    const header = try generateHeader(allocator);
    defer allocator.free(header);

    // Write to file using the Io API
    const file = try std.Io.Dir.cwd().createFile(init.io, output_path, .{});
    defer file.close(init.io);

    var buf: [4096]u8 = undefined;
    var writer = file.writer(init.io, &buf);
    try writer.interface.writeAll(header);
    try writer.flush();

    std.debug.print("Generated header: {s}\n", .{output_path});
}

