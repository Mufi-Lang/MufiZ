        \\#define MUFIZ_H
        \\
        \\#include <stdint.h>
        \\#include <stdbool.h>
        \\#include <stddef.h>
        \\
        \\#ifdef __cplusplus
        \\extern "C" {
        \\#endif
        \\
        \\// ============================================================================
        \\// Platform-specific export/import macros
        \\// ============================================================================
        \\
        \\#if defined(_WIN32) || defined(__CYGWIN__)
        \\  #if defined(MUFIZ_BUILDING_LIBRARY)
        \\    #define MUFIZ_API __declspec(dllexport)
        \\  #else
        \\    #define MUFIZ_API __declspec(dllimport)
        \\  #endif
        \\#else
        \\  #if defined(__GNUC__) && __GNUC__ >= 4
        \\    #define MUFIZ_API __attribute__((visibility("default")))
        \\  #else
        \\    #define MUFIZ_API
        \\  #endif
        \\#endif
